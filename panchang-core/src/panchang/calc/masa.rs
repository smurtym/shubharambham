use crate::panchang::calc::VedicDay;

use crate::panchang::output_structure::*;
use auto_bench_fct::auto_bench_fct;

impl VedicDay {
    #[auto_bench_fct]
    pub fn masa(&self) -> (i32, i32, Masa) {

        let masa_result = MASA.iter().rev()
                    .find(|&&(dt, _)| dt < self.sun_rise)
                    .map(|&(_, masa)| masa)
                    .unwrap();

        let samvatsara = masa_result/1000;
        let masa = masa_result % 100;
        let masa_type = (masa_result % 1000) / 100;

        let purva_ritu = match masa {
            1 | 2 => 1, // Vasanta
            3 | 4 => 2, // Grishma
            5 | 6 => 3, // Varsha
            7 | 8 => 4, // Sharada
            9 | 10 => 5, // Hemanta
            11 | 12 => 6, // Shishira
            _ => 0, // Invalid masa
        };

        (
            samvatsara,
            purva_ritu,
            Masa {
                is_adhika: masa_type & 1 == 1,
                is_nija: masa_type & 2 == 2,
                is_kshaya: masa_type & 4 == 4,
                id: masa,
            },
        )
    }

}

